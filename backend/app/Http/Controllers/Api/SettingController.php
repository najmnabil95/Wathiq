<?php

namespace App\Http\Controllers\Api;

use App\Http\Controllers\Controller;
use App\Models\Category;
use App\Models\Document;
use App\Models\DocumentType;
use App\Models\Setting;
use App\Models\User;
use App\Services\AuditService;
use Illuminate\Http\JsonResponse;
use Illuminate\Http\Request;

class SettingController extends Controller
{
    public const DEFAULTS = [
        'numbering_pattern'  => '{CAT}-{YEAR}-{SEQ:4}',
        'retention_years'    => '7',
        'require_mfa'        => true,
        'sha_check_enabled'  => true,
        'watermark_downloads'=> true,
    ];

    public function __construct(private readonly AuditService $auditService) {}

    public function index(Request $request): JsonResponse
    {
        $this->checkPermission('settings.view');

        return response()->json([
            'success' => true,
            'data'    => $this->currentSettings(),
        ]);
    }

    public function update(Request $request): JsonResponse
    {
        $this->checkPermission('settings.manage');

        $validated = $request->validate([
            'numbering_pattern' => ['sometimes', 'string', 'max:120', 'regex:/^[\p{L}\p{N}{}\-_:.\[\]\s]+$/u'],
            'retention_years'   => ['sometimes', 'string', 'in:3,5,7,10,99'],
            'require_mfa'       => ['sometimes', 'boolean'],
            'sha_check_enabled' => ['sometimes', 'boolean'],
            'watermark_downloads' => ['sometimes', 'boolean'],
        ]);

        $before = $this->currentSettings();

        foreach ($validated as $key => $value) {
            Setting::put($key, $value, 'archive');
        }

        $after = $this->currentSettings();

        $this->auditService->log(
            'settings.update',
            null,
            $before,
            $after,
            'System and archiving settings updated by ' . $request->user()->name
        );

        return response()->json([
            'success' => true,
            'message' => 'تم حفظ إعدادات النظام وسياسات الأرشفة بنجاح.',
            'data'    => $after,
        ]);
    }

    public function backup(Request $request): JsonResponse
    {
        $this->checkPermission('settings.backup');

        $payload = [
            'export_date' => now()->toIso8601String(),
            'version'     => 'IT-EDMS v2.4 Enterprise',
            'exported_by' => $request->user()->email,
            'settings'    => $this->currentSettings(),
            'counts'      => [
                'documents'      => Document::count(),
                'users'          => User::count(),
                'categories'     => Category::count(),
                'document_types' => DocumentType::count(),
            ],
        ];

        $this->auditService->log(
            'settings.backup',
            null,
            null,
            ['export_date' => $payload['export_date']],
            'Configuration backup generated by ' . $request->user()->name
        );

        return response()->json(['success' => true, 'data' => $payload]);
    }

    private function currentSettings(): array
    {
        return array_merge(self::DEFAULTS, Setting::allAsMap());
    }

    private function checkPermission(string $perm): void
    {
        $user = request()->user();

        if (!$user) {
            abort(401, 'غير مصرح.');
        }

        if (!$user->hasPermission($perm) && !$user->isSuperAdmin()) {
            abort(403, 'ليس لديك صلاحية للقيام بهذه العملية.');
        }
    }
}
